"""Deriving fix.files and fix.symbols from the fix commit (plan.md section 3.3)."""

from __future__ import annotations

from pathlib import Path

import pytest
import yaml

from segbench.corpus.derive import (
    DerivedFix,
    DeriveError,
    derive_fix,
    go_symbols,
    python_symbols,
    write_derived_fix,
)


def test_derive_reports_every_changed_file(fix_repo: Path) -> None:
    derived = derive_fix(fix_repo, "HEAD")

    assert derived.files == ["README.md", "main.go", "pkg/mod.py"]


def test_derive_reports_only_the_changed_symbols(fix_repo: Path) -> None:
    derived = derive_fix(fix_repo, "HEAD")

    assert derived.symbols == ["Driver.stop", "Server.Handle"]


def test_derive_resolves_the_ref_to_a_full_hash(fix_repo: Path) -> None:
    derived = derive_fix(fix_repo, "HEAD")

    assert len(derived.commit) == 40


def test_derive_rejects_a_directory_that_is_not_a_repository(tmp_path: Path) -> None:
    with pytest.raises(DeriveError, match="not a git repository"):
        derive_fix(tmp_path, "HEAD")


def test_derive_rejects_an_unknown_commit(fix_repo: Path) -> None:
    with pytest.raises(DeriveError, match="rev-parse"):
        derive_fix(fix_repo, "does-not-exist")


# --- Python symbol extraction --------------------------------------------------------------


PY_SOURCE = """\
import os


def module_level():
    return 1


class Driver:
    def start(self):
        return 2

    @property
    def name(self):
        return "d"
"""


@pytest.mark.parametrize(
    ("line", "expected"),
    [
        (5, ["module_level"]),
        (10, ["Driver.start"]),
        (14, ["Driver.name"]),
        (1, []),
    ],
)
def test_python_symbols_covering_a_changed_line(line: int, expected: list[str]) -> None:
    assert python_symbols(PY_SOURCE, {line}) == expected


def test_python_decorator_line_belongs_to_its_function() -> None:
    assert python_symbols(PY_SOURCE, {12}) == ["Driver.name"]


def test_python_reports_the_method_rather_than_its_enclosing_class() -> None:
    """`Driver.start` is the answer the grader's symbol_hit wants; `Driver` alone is noise."""
    assert python_symbols(PY_SOURCE, {10}) == ["Driver.start"]


def test_python_unparseable_source_yields_no_symbols_rather_than_failing() -> None:
    assert python_symbols("def broken(:\n", {1}) == []


