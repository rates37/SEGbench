# --- languages with no extractor -------------------------------------------------------------


def test_symbols_are_null_when_no_language_is_supported(fix_repo: Path, tmp_path: Path) -> None:
    """Null, not empty: the grader redistributes the symbol weight (plan.md section 7.3)."""
    import subprocess

    (fix_repo / "notes.rst").write_text("changed\n", encoding="utf-8")
    subprocess.run(["git", "-C", str(fix_repo), "add", "-A"], check=True, capture_output=True)
    subprocess.run(
        ["git", "-C", str(fix_repo), "commit", "-qm", "docs only"], check=True, capture_output=True
    )

    derived = derive_fix(fix_repo, "HEAD")

    assert derived.files == ["notes.rst"]
    assert derived.symbols is None


# --- writing the result back -----------------------------------------------------------------


GROUND_TRUTH = """\
root_cause: |
  Something went wrong.
component: nova
fix:
  commit: TODO
  url: null
  # files and symbols are generated by `segbench corpus derive`.
  files: []
  symbols: null
provenance: inferred
reviewed_by: null
"""


def test_write_derived_fix_populates_both_fields(tmp_path: Path) -> None:
    path = tmp_path / "ground_truth.yaml"
    path.write_text(GROUND_TRUTH, encoding="utf-8")

    write_derived_fix(path, DerivedFix(commit="abc", files=["a/b.py"], symbols=["C.d"]))

    loaded = yaml.safe_load(path.read_text(encoding="utf-8"))
    assert loaded["fix"]["files"] == ["a/b.py"]
    assert loaded["fix"]["symbols"] == ["C.d"]


def test_write_derived_fix_preserves_the_rest_of_the_file(tmp_path: Path) -> None:
    """These files are hand-maintained; a YAML round-trip would silently eat every comment."""
    path = tmp_path / "ground_truth.yaml"
    path.write_text(GROUND_TRUTH, encoding="utf-8")

    write_derived_fix(path, DerivedFix(commit="abc", files=["a/b.py"], symbols=None))

    text = path.read_text(encoding="utf-8")
    assert "# files and symbols are generated" in text
    assert "provenance: inferred" in text
    assert "Something went wrong." in text
    assert yaml.safe_load(text)["fix"]["symbols"] is None


def test_write_derived_fix_is_idempotent(tmp_path: Path) -> None:
    path = tmp_path / "ground_truth.yaml"
    path.write_text(GROUND_TRUTH, encoding="utf-8")
    derived = DerivedFix(commit="abc", files=["a/b.py", "c/d.py"], symbols=["E.f"])

    write_derived_fix(path, derived)
    once = path.read_text(encoding="utf-8")
    write_derived_fix(path, derived)

    assert path.read_text(encoding="utf-8") == once


def test_write_derived_fix_needs_a_fix_block(tmp_path: Path) -> None:
    path = tmp_path / "ground_truth.yaml"
    path.write_text("component: nova\n", encoding="utf-8")

    with pytest.raises(DeriveError, match="no top-level 'fix:' block"):
        write_derived_fix(path, DerivedFix(commit="abc", files=[], symbols=None))
